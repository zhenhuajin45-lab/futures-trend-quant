from __future__ import absolute_import, print_function

import os
import sys

from gm.api import ADJUST_NONE, MODE_BACKTEST, run


PROJECT_ROOT = os.environ.get("FUTURES_TREND_QUANT_ROOT", r"E:\掘金\期货")
if PROJECT_ROOT not in sys.path:
    sys.path.insert(0, PROJECT_ROOT)

from futures_trend_quant.live.gm_strategy import (
    init as strategy_init,
    on_bar as strategy_on_bar,
    on_error as strategy_on_error,
)


def init(context):
    return strategy_init(context)


def on_bar(context, bars):
    return strategy_on_bar(context, bars)


def on_error(context, code, info):
    return strategy_on_error(context, code, info)


if __name__ == "__main__":
    run(
        strategy_id=os.environ.get("GM_STRATEGY_ID", "<strategy-id>"),
        filename="main.py",
        mode=MODE_BACKTEST,
        token=os.environ.get("GM_TOKEN", ""),
        backtest_start_time="2026-10-20 08:00:00",
        backtest_end_time="2026-10-20 09:16:00",
        backtest_adjust=ADJUST_NONE,
        backtest_initial_cash=10_000_000,
        backtest_commission_ratio=0.0001,
        backtest_slippage_ratio=0.0001,
        backtest_match_mode=1,
    )
